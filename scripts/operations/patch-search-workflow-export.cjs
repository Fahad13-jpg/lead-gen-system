'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const [beforePath,sourcePath,outputPath]=process.argv.slice(2);
if(!beforePath||!sourcePath||!outputPath)throw Error('Expected exported workflow, source workflow, and output paths');
const exported=JSON.parse(fs.readFileSync(beforePath,'utf8'));
const previous=Array.isArray(exported)?exported[0]:exported;
assert(previous&&(!Array.isArray(exported)||exported.length===1));
const source=JSON.parse(fs.readFileSync(sourcePath,'utf8'));
assert.equal(source.name,previous.name,'Workflow name changed');
const oldNode=previous.nodes.find(node=>node.name==='Transform Results');
const newNode=source.nodes.find(node=>node.name==='Transform Results');
assert(oldNode&&newNode&&oldNode.type===newNode.type,'Result node missing or changed');
assert.match(newNode.parameters.jsCode,/mismatchedUniversity/);
assert.match(newNode.parameters.jsCode,/excludedCategory/);
new Function(newNode.parameters.jsCode);
const patched=structuredClone(previous);
patched.nodes.find(node=>node.name==='Transform Results').parameters.jsCode=newNode.parameters.jsCode;
patched.active=false;
assert.equal(patched.id,previous.id);
assert.equal(patched.nodes.length,previous.nodes.length);
assert.deepEqual(patched.connections,previous.connections);
fs.writeFileSync(outputPath,JSON.stringify([patched]));
console.log(JSON.stringify({id:patched.id,name:patched.name,was_active:previous.active,only_result_code_changed:true}));
